/// 3×5 bitmap font for the Station layout; bit 2 is the leftmost pixel.
/// Keep the existing 5×7 font for larger event counters.
pub fn glyph(ch: char) -> [u8; 5] {
    let ch = match ch.to_ascii_uppercase() {
        'À' | 'Â' | 'Ä' | 'à' | 'â' | 'ä' | 'Æ' | 'æ' => 'A',
        'Ç' | 'ç' => 'C',
        'É' | 'È' | 'Ê' | 'Ë' | 'é' | 'è' | 'ê' | 'ë' => 'E',
        'Î' | 'Ï' | 'î' | 'ï' => 'I',
        'Ô' | 'Ö' | 'ô' | 'ö' | 'Œ' | 'œ' => 'O',
        'Ù' | 'Û' | 'Ü' | 'ù' | 'û' | 'ü' => 'U',
        'Ÿ' | 'ÿ' => 'Y',
        '\u{00a0}' => ' ',
        '\u{2018}' | '\u{2019}' => '\'',
        '\u{2013}' | '\u{2014}' => '-',
        ch => ch,
    };
    match ch {
        ' ' => [0, 0, 0, 0, 0],
        'A' => [2, 5, 7, 5, 5],
        'B' => [6, 5, 6, 5, 6],
        'C' => [3, 4, 4, 4, 3],
        'D' => [6, 5, 5, 5, 6],
        'E' => [7, 4, 6, 4, 7],
        'F' => [7, 4, 6, 4, 4],
        'G' => [3, 4, 5, 5, 3],
        'H' => [5, 5, 7, 5, 5],
        'I' => [7, 2, 2, 2, 7],
        'J' => [1, 1, 1, 5, 2],
        'K' => [5, 5, 6, 5, 5],
        'L' => [4, 4, 4, 4, 7],
        'M' => [5, 7, 7, 5, 5],
        'N' => [5, 7, 7, 7, 5],
        'O' => [2, 5, 5, 5, 2],
        'P' => [6, 5, 6, 4, 4],
        'Q' => [2, 5, 5, 7, 3],
        'R' => [6, 5, 6, 5, 5],
        'S' => [3, 4, 2, 1, 6],
        'T' => [7, 2, 2, 2, 2],
        'U' => [5, 5, 5, 5, 7],
        'V' => [5, 5, 5, 5, 2],
        'W' => [5, 5, 7, 7, 5],
        'X' => [5, 5, 2, 5, 5],
        'Y' => [5, 5, 2, 2, 2],
        'Z' => [7, 1, 2, 4, 7],
        '0' => [7, 5, 5, 5, 7],
        '1' => [2, 6, 2, 2, 7],
        '2' => [6, 1, 2, 4, 7],
        '3' => [6, 1, 2, 1, 6],
        '4' => [5, 5, 7, 1, 1],
        '5' => [7, 4, 6, 1, 6],
        '6' => [3, 4, 7, 5, 7],
        '7' => [7, 1, 2, 2, 2],
        '8' => [7, 5, 7, 5, 7],
        '9' => [7, 5, 7, 1, 6],
        ':' => [0, 2, 0, 2, 0],
        '-' => [0, 0, 7, 0, 0],
        '/' => [1, 1, 2, 4, 4],
        '.' => [0, 0, 0, 0, 2],
        '+' => [0, 2, 7, 2, 0],
        '>' => [4, 2, 1, 2, 4],
        '!' => [2, 2, 2, 0, 2],
        '\'' => [2, 2, 0, 0, 0],
        '(' => [1, 2, 2, 2, 1],
        ')' => [4, 2, 2, 2, 4],
        '[' => [3, 2, 2, 2, 3],
        ']' => [6, 2, 2, 2, 6],
        '&' => [2, 5, 2, 5, 3],
        '°' => [6, 6, 0, 0, 0],
        _ => [6, 1, 2, 0, 2],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compact_french_names_remain_visible() {
        for ch in "RÉPUBLIQUE GUILLAUMIN Frédéric ÀÇÉÈÊËÎÏÔÖÙÛÜŒœ".chars() {
            let pixels = glyph(ch);
            assert!(pixels.iter().all(|row| *row < 8));
            if !ch.is_whitespace() {
                assert_ne!(pixels, [0; 5], "{ch} must not disappear");
            }
        }
    }
}
